/** 获取一级分类（没有 parentId 的） */
export function getRootCategories(): ForumCategory[] {
  return forumCategories.filter((c) => !c.parentId);
}

/** 获取某个分类的子分类 */
export function getChildCategories(parentId: string): ForumCategory[] {
  return forumCategories.filter((c) => c.parentId === parentId);
}

/** 根据 slug 查找分类 */
export function getCategoryBySlug(slug: string): ForumCategory | undefined {
  return forumCategories.find((c) => c.slug === slug);
}
